create extension if not exists pgcrypto;

create table if not exists public.rooms (
  id uuid primary key default gen_random_uuid(),
  code text unique not null check (code ~ '^[0-9]{4}$'),
  host_key text not null,
  topic text not null default '요즘 내가 가장 재미있게 하는 것은?',
  duration_sec integer not null default 300 check (duration_sec between 60 and 900),
  difficulty text not null default 'normal' check (difficulty in ('easy','normal','hard')),
  status text not null default 'lobby' check (status in ('lobby','chat','vote','reveal','closed')),
  created_at timestamptz not null default now(),
  started_at timestamptz,
  ends_at timestamptz,
  last_ai_at timestamptz
);

create table if not exists public.participants (
  id uuid primary key default gen_random_uuid(),
  room_id uuid not null references public.rooms(id) on delete cascade,
  participant_key text not null,
  nickname text not null,
  emoji text not null,
  is_ai boolean not null default false,
  joined_at timestamptz not null default now(),
  unique(room_id, participant_key),
  unique(room_id, nickname)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.rooms(id) on delete cascade,
  participant_id uuid not null references public.participants(id) on delete cascade,
  nickname text not null,
  emoji text not null,
  body text not null check (char_length(body) between 1 and 120),
  created_at timestamptz not null default now()
);

create table if not exists public.votes (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.rooms(id) on delete cascade,
  voter_participant_id uuid not null references public.participants(id) on delete cascade,
  target_participant_id uuid not null references public.participants(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(room_id, voter_participant_id)
);

create index if not exists messages_room_id_id_idx on public.messages(room_id,id);
create index if not exists participants_room_id_idx on public.participants(room_id);
create index if not exists votes_room_id_idx on public.votes(room_id);

alter table public.rooms enable row level security;
alter table public.participants enable row level security;
alter table public.messages enable row level security;
alter table public.votes enable row level security;

